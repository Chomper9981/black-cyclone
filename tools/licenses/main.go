// Command licenses collects the license texts of every Go module compiled into
// a build, plus the Go standard library, into one text file. MIT, BSD and
// Apache-2.0 all require their notices to travel with binary releases.
//
// Regenerate after changing dependencies (see THIRD_PARTY_NOTICES.md):
//
//	go run ./tools/licenses -goos windows,linux -tags desktop,production -o licenses/go-desktop.txt .
//	go run ./tools/licenses -C mobile/core -goos android -o licenses/go-android.txt ./rcvcore golang.org/x/mobile/bind/seq
package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

type module struct{ path, version, dir string }

func main() {
	dir := flag.String("C", ".", "directory of the Go module to inspect")
	goos := flag.String("goos", "windows,linux", "comma-separated target systems")
	tags := flag.String("tags", "", "build tags")
	out := flag.String("o", "", "output file")
	flag.Parse()
	if *out == "" || flag.NArg() == 0 {
		fmt.Fprintln(os.Stderr, "usage: licenses [-C dir] [-goos list] [-tags list] -o out.txt packages...")
		os.Exit(2)
	}

	mods := map[string]module{}
	for _, g := range strings.Split(*goos, ",") {
		args := []string{"list", "-deps", "-f", "{{with .Module}}{{if not .Main}}{{.Path}}\t{{.Version}}\t{{.Dir}}{{end}}{{end}}"}
		if *tags != "" {
			args = append(args, "-tags", *tags)
		}
		args = append(args, flag.Args()...)
		cmd := exec.Command("go", args...)
		cmd.Dir = *dir
		cmd.Env = append(os.Environ(), "GOOS="+g, "CGO_ENABLED=1")
		cmd.Stderr = os.Stderr
		data, err := cmd.Output()
		if err != nil {
			fail(fmt.Errorf("go list (GOOS=%s): %w", g, err))
		}
		sc := bufio.NewScanner(bytes.NewReader(data))
		for sc.Scan() {
			f := strings.Split(sc.Text(), "\t")
			if len(f) == 3 && f[2] != "" {
				mods[f[0]] = module{f[0], f[1], f[2]}
			}
		}
	}

	goroot, err := exec.Command("go", "env", "GOROOT").Output()
	if err != nil {
		fail(err)
	}
	goVer, err := exec.Command("go", "env", "GOVERSION").Output()
	if err != nil {
		fail(err)
	}

	paths := make([]string, 0, len(mods))
	for p := range mods {
		paths = append(paths, p)
	}
	sort.Strings(paths)

	var b strings.Builder
	b.WriteString("Licenses of the Go code compiled into this program.\n")
	b.WriteString("Generated by tools/licenses; do not edit by hand.\n")
	section(&b, "Go standard library "+strings.TrimSpace(string(goVer)), strings.TrimSpace(string(goroot)))
	for _, p := range paths {
		m := mods[p]
		section(&b, m.path+" "+m.version, m.dir)
	}
	if err := os.WriteFile(*out, []byte(b.String()), 0o644); err != nil {
		fail(err)
	}
	fmt.Printf("%s: %d modules + Go standard library\n", *out, len(paths))
}

// section appends every license and NOTICE file found at the top of dir.
func section(b *strings.Builder, title, dir string) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		fail(err)
	}
	found := false
	for _, e := range entries {
		name := strings.ToUpper(e.Name())
		if e.IsDir() || !(strings.HasPrefix(name, "LICEN") || strings.HasPrefix(name, "COPYING") || strings.HasPrefix(name, "NOTICE")) {
			continue
		}
		text, err := os.ReadFile(filepath.Join(dir, e.Name()))
		if err != nil {
			fail(err)
		}
		fmt.Fprintf(b, "\n%s\n%s (%s)\n%s\n\n", strings.Repeat("=", 78), title, e.Name(), strings.Repeat("=", 78))
		b.WriteString(strings.TrimRight(strings.ReplaceAll(string(text), "\r\n", "\n"), "\n") + "\n")
		found = true
	}
	if !found {
		fail(fmt.Errorf("no license file in %s (%s)", dir, title))
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "licenses:", err)
	os.Exit(1)
}
